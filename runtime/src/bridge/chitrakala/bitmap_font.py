class BitmapFont:
    """
    Bitmap font renderer.
    
    Attributes:
        char_width: Width of each character (8 pixels)
        char_height: Height of each character (8 pixels)
        font_data: Dictionary of character bitmaps
    """
    
    def __init__(self, font_data: Dict[int, List[int]] = None):
        """Initialize font with optional custom font data."""
        self.char_width = 8
        self.char_height = 8
        self.font_data = font_data or FONT_8x8
    
    def get_char_bitmap(self, char: str) -> List[int]:
        """Get bitmap data for a character."""
        code = ord(char)
        return self.font_data.get(code, [0] * 8)  # Return blank if not found
    
    def render_char(self, canvas: ChitraCanvas, x: int, y: int, char: str, color: ChitraColor):
        """
        Render a single character onto canvas.
        
        Args:
            canvas: Canvas to render on
            x, y: Top-left position
            char: Character to render
            color: Color to use
        """
        bitmap = self.get_char_bitmap(char)
        
        for row_idx, row_data in enumerate(bitmap):
            for col in range(8):
                # Check if bit is set (MSB first)
                if row_data & (0x80 >> col):
                    canvas.set_pixel(x + col, y + row_idx, color)
    
    def measure_text(self, text: str) -> Tuple[int, int]:
        """Get width and height of text in pixels."""
        return len(text) * self.char_width, self.char_height


def draw_text(canvas: ChitraCanvas, x: int, y: int, text: str, color, 
              font: BitmapFont = None, scale: int = 1):
    """
    Draw text onto canvas.
    
    Args:
        canvas: Canvas to draw on
        x, y: Top-left position
        text: Text string to render
        color: Color (name or ChitraColor)
        font: BitmapFont instance (default: 8x8 font)
        scale: Scaling factor (1 = 8x8, 2 = 16x16, etc.)
        
    Note:
        Text is drawn left-to-right, top-to-bottom.
        Characters outside canvas bounds are clipped.
    """
    if isinstance(color, str):
        color = get_color(color)
    
    font = font or BitmapFont()
    
    current_x = x
    for char in text:
        if char == '\n':
            # New line
            current_x = x
            y += font.char_height * scale
            continue
        elif char == ' ':
            # Space
            current_x += font.char_width * scale
            continue
        
        if scale == 1:
            font.render_char(canvas, current_x, y, char, color)
        else:
            # Scaled rendering
            bitmap = font.get_char_bitmap(char)
            for row_idx, row_data in enumerate(bitmap):
                for col in range(8):
                    if row_data & (0x80 >> col):
                        # Draw scaled pixel
                        for sy in range(scale):
                            for sx in range(scale):
                                canvas.set_pixel(
                                    current_x + col * scale + sx,
                                    y + row_idx * scale + sy,
                                    color
                                )
        
        current_x += font.char_width * scale


def draw_text_centered(canvas: ChitraCanvas, y: int, text: str, color,
                       font: BitmapFont = None, scale: int = 1):
    """
    Draw text centered horizontally on canvas.
    
    Args:
        canvas: Canvas to draw on
        y: Y position
        text: Text string
        color: Color
        font: BitmapFont instance
        scale: Scaling factor
    """
    font = font or BitmapFont()
    text_width = len(text) * font.char_width * scale
    x = (canvas.width - text_width) // 2
    draw_text(canvas, x, y, text, color, font, scale)
